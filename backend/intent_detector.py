# Maps Canadian Express Entry follow-up questions to CanPR.ai backend functions.
# Uses phrase matching first and falls back to Claude when no intent is clear.

from __future__ import annotations

import re
import unicodedata


def normalize_question(question: str) -> str:
    """Normalize punctuation and spacing without changing the user's meaning."""
    q = unicodedata.normalize("NFKC", question).lower()
    q = q.replace("’", "'").replace("`", "'")
    q = re.sub(r"[-–—]", " ", q)
    q = re.sub(r"[^\w\s'+.]", " ", q)
    q = re.sub(r"\s+", " ", q)
    return q.strip()


