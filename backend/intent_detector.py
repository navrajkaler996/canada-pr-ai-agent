def _contains_any(q: str, keywords: list[str]) -> bool:
    return any(keyword in q for keyword in keywords)


def detect_intent(question: str) -> dict | None:
    q = normalize_question(question)

    # Order matters. Hypothetical calculations and explicit comparisons are
    # checked before draw/timeline/improvement intents.
    if _contains_any(q, COMPARE_KEYWORDS):
        return {
            "intent": "compare_scenarios",
            "instruction": (
                "User wants to compare two options or scenarios. "
                "Call get_active_profile first to get the exact profile. "
                "Identify the two scenarios the user is comparing. "
                "Call compare_scenarios with both modified profiles. "
                "Present the difference clearly."
            ),
        }

    if _contains_any(q, SCENARIO_KEYWORDS):
        return {
            "intent": "scenario_simulation",
            "instruction": (
                "User is asking about a hypothetical scenario change to their profile. "
                "Call get_active_profile first to get the exact profile. "
                "Identify what field the user wants to change based on their question. "
                "Then call calculate_crs with only that field modified. "
                "Never modify fields the user did not mention."
            ),
        }

    if _contains_any(q, DRAW_KEYWORDS):
        return {
            "intent": "draw_history",
            "instruction": (
                "User wants draw history information. "
                "Identify the stream or category from the question. "
                "Use these exact keywords for get_draw_history: "
                "'health' for Healthcare, 'STEM' for STEM, 'education' for Education, "
                "'trade' for Trades, 'transport' for Transportation, "
                "'agriculture' for Agriculture, 'manager' for Business, "
                "'Canadian Experience Class' for CEC, 'Federal Skilled Worker' for FSW, "
                "'French' for French category. "
                "If no specific stream is mentioned, use the user's eligible stream from context."
            ),
        }

    if _contains_any(q, ITA_KEYWORDS):
        return {
            "intent": "ita_timeline",
            "instruction": (
                "User wants to know about ITA likelihood or timeline. "
                "Call estimate_ita_timeline with the user's CRS score from context "
                "and their primary eligible stream. "
                "Do not guess the score; use the one stored in session context."
            ),
        }

    if _contains_any(q, IMPROVE_KEYWORDS):
        return {
            "intent": "improve_score",
            "instruction": (
                "User wants to know how to improve their CRS score. "
                "Call get_active_profile first to get the exact profile. "
                "Then call get_score_gaps with that profile. "
                "Present improvements ranked by points gained, highest first."
            ),
        }

    return None


